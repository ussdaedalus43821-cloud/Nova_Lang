"""The workload group of the benchmark suite (M12 slice 1): programs that do real work, run in-process.

`run.py --only workloads` runs it; `run.py` runs it with the other groups. It measures three families:

  micro   about a dozen small programs, each stressing one thing a NovaLang program does (recursion, integer loops,
          string building, split/join, lists and dictionaries, closures, higher-order library calls, try/catch,
          nested indexing, a character loop, float math, a module-heavy start-up) plus the four older tests/bench programs;
  poc     the four proof-of-concept apps' real programs, vendored in workloads/poc/ (see VENDORED.md there):
          Nova_Data (CSV report), Nova_Log (access-log parser), Nova_Stats (one dashboard tick on recorded fixtures);
  full    (--full) the 50 MB Nova_Log benchmark, a few samples, trusted only.

Every workload is timed on the bytecode VM under the `trusted` profile and under `restricted` with the limit checks on
(limits raised only as far as the program needs, never lowered), so the price of M11 is a number per program. Each row
also carries `compile_ms`: the lex + parse + compile time of the program, so that start-up work (what a bytecode cache
can remove) is reported next to execution work (what only a faster VM can remove): the M12 plan's decision D4.

Programs run inside this process (no interpreter start-up in the numbers), with their output discarded. Data files are
generated by the vendored seeded generators into a temporary folder and are identical on every run.
"""

import contextlib
import gc
import io
import os
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORK = HERE / "workloads"
sys.path.insert(0, str(ROOT))

import novalang as nl  # noqa: E402

# (name, path relative to workloads/micro or to the repository, what one run does)
MICRO = [
    ("recursion (fib 23)", "micro/recursion.nova"),
    ("integer arithmetic loop (100k)", "micro/arithmetic.nova"),
    ("float math and library math (60k)", "micro/float_math.nova"),
    ("string building (40k appends)", "micro/string_build.nova"),
    ("character loop over a string", "micro/string_scan.nova"),
    ("split / trim / upper / join (40k rows)", "micro/split_join.nova"),
    ("list append and dictionary updates (50k)", "micro/list_dict.nova"),
    ("map / filter / reduce with callbacks", "micro/higher_order.nova"),
    ("try / catch in a loop (40k)", "micro/try_catch.nova"),
    ("nested indexing: 36x36 matrix product", "micro/matrix.nova"),
    ("module-heavy start-up (2 library modules)", "micro/modules_startup.nova"),
    ("std:decimal ledger step (3k x 11 operations)", "micro/decimal.nova"),
    ("std:regex status extraction (3k lines) and a long split", "micro/regex.nova"),
    ("older: closures (100k calls)", "../../../bench/closures.nova"),
    ("older: loops (200k iterations)", "../../../bench/loops.nova"),
    ("older: index assignment (550k stores)", "../../../bench/index_assign.nova"),
    ("older: fib(22)", "../../../bench/fib22.nova"),
]

LOG_MB = 5          # the default Nova_Log workload; --full adds the 50 MB one
RESTRICTED_LOG_MB = 0.9   # a log that fits the restricted profile's 1,000,000-character string limit


def sample(function, repeat, warmup=None):
    if warmup is None:
        warmup = int(os.environ.get("NOVA_BENCH_WARMUP", "1"))     # a JIT such as PyPy needs more than one
    for _ in range(warmup):
        function()
    times = []
    for _ in range(repeat):
        gc.collect()
        gc.disable()
        try:
            start = time.perf_counter()
            function()
            times.append(time.perf_counter() - start)
        finally:
            gc.enable()
    return times


def capabilities(profile, grants):
    if profile == "trusted":
        return None
    # The limits a real run may need are raised (steps, time, output only); string/list/dict stay at their defaults.
    return nl.Capabilities(profile="restricted", limits={"steps": 2_000_000_000, "time": 3_600_000, "output": 100_000_000},
                           **grants)


def run_once(path, argv, profile, grants, cwd=None):
    """Run one NovaLang file to its end in this process; the exit code. Output is discarded."""
    path = str(path)
    source = Path(path).read_text(encoding="utf-8")
    here = os.getcwd()
    saved = nl.SCRIPT_ARGS
    nl.SCRIPT_ARGS = list(argv)
    interpreter = nl.Interpreter("vm", capabilities=capabilities(profile, grants))
    interpreter.file_stack.append(os.path.dirname(os.path.abspath(path)))
    out = io.StringIO()
    code = 0
    try:
        if cwd:
            os.chdir(cwd)
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            try:
                nl.run(source, interpreter)
            except nl.ProgramExit as stop:
                code = stop.code
    finally:
        os.chdir(here)
        nl.SCRIPT_ARGS = saved
    if code != 0:
        raise SystemExit("workload failed ({}, {}): exit {}\n{}".format(path, profile, code, out.getvalue()[-600:]))
    return out.getvalue()


def compile_ms(path):
    source = Path(path).read_text(encoding="utf-8")
    times = sample(lambda: nl.compile_source(source), 7)
    return statistics.median(times) * 1000


def row(name, family, profile, times, units=None, unit="", compile_time=None, note=""):
    median = statistics.median(times)
    out = {"group": "workloads", "family": family, "name": name, "profile": profile,
           "median_ms": median * 1000, "min_ms": min(times) * 1000, "max_ms": max(times) * 1000,
           "spread": (max(times) - min(times)) / median if median else 0.0, "samples": len(times),
           "samples_ms": [round(t * 1000, 3) for t in times], "note": note}
    if units:
        out["per_second"] = units / median
        out["unit"] = unit
    if compile_time is not None:
        out["compile_ms"] = compile_time
        out["compile_share"] = compile_time / (median * 1000) if median else 0.0
    return out


def generate(command, destination):
    done = subprocess.run([sys.executable] + command, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit("generator failed: {}\n{}".format(command, done.stderr[-400:]))
    return done.stdout.strip()


def count_lines(path):
    with open(path, "rb") as handle:
        return sum(1 for _ in handle)


def workloads(repeat, full=False, log_file=None):
    rows = []
    restricted_ok = not nl.SANDBOX_UNSUPPORTED
    with tempfile.TemporaryDirectory(prefix="nova-workloads-") as folder:
        folder = os.path.realpath(folder)
        # ---- micro programs
        for name, relative in MICRO:
            path = (WORK / relative).resolve() if relative.startswith("micro") else (WORK / "micro" / relative).resolve()
            grants = {"import_from": [str(ROOT)]}
            c = compile_ms(path)
            rows.append(row(name, "micro", "trusted", sample(lambda: run_once(path, [], "trusted", {}), repeat),
                            compile_time=c))
            if restricted_ok:
                rows.append(row(name, "micro", "restricted",
                                sample(lambda: run_once(path, [], "restricted", grants), repeat), compile_time=c))
        # ---- Nova_Data: 10,000 CSV rows
        csv_path = os.path.join(folder, "transactions.csv")
        generate([str(WORK / "poc/nova_data/make_csv.py"), csv_path, "10000"], csv_path)
        data_program = WORK / "poc/nova_data/nova_data.nova"
        data_grants = {"read": [folder], "process": True, "clock": True}
        c = compile_ms(data_program)
        rows.append(row("Nova_Data: 10,000 CSV rows", "poc", "trusted",
                        sample(lambda: run_once(data_program, [csv_path], "trusted", {}), repeat), 10000, "rows/s", c))
        if restricted_ok:
            rows.append(row("Nova_Data: 10,000 CSV rows", "poc", "restricted",
                            sample(lambda: run_once(data_program, [csv_path], "restricted", data_grants), repeat),
                            10000, "rows/s", c))
        # ---- Nova_Log
        log_program = WORK / "poc/nova_log/nova_log.nova"
        c = compile_ms(log_program)
        log_path = os.path.join(folder, "access.log")
        generate([str(WORK / "poc/nova_log/make_log.py"), log_path, str(LOG_MB)], log_path)
        lines = count_lines(log_path)
        rows.append(row("Nova_Log: {} MB synthetic access log".format(LOG_MB), "poc", "trusted",
                        sample(lambda: run_once(log_program, [log_path], "trusted", {}), repeat), lines, "lines/s", c,
                        note="{:,} lines".format(lines)))
        if restricted_ok:
            small_path = os.path.join(folder, "small.log")
            generate([str(WORK / "poc/nova_log/make_log.py"), small_path, str(RESTRICTED_LOG_MB)], small_path)
            small_lines = count_lines(small_path)
            log_grants = {"read": [folder], "process": True, "clock": True}
            rows.append(row("Nova_Log: {} MB log (fits the sandbox string limit)".format(RESTRICTED_LOG_MB), "poc",
                            "trusted", sample(lambda: run_once(log_program, [small_path], "trusted", {}), repeat),
                            small_lines, "lines/s", c, note="{:,} lines".format(small_lines)))
            rows.append(row("Nova_Log: {} MB log (fits the sandbox string limit)".format(RESTRICTED_LOG_MB), "poc",
                            "restricted", sample(lambda: run_once(log_program, [small_path], "restricted", log_grants),
                                                 repeat), small_lines, "lines/s", c, note="{:,} lines".format(small_lines)))
        if log_file:
            n = count_lines(log_file)
            rows.append(row("Nova_Log: {}".format(os.path.basename(log_file)), "poc", "trusted",
                            sample(lambda: run_once(log_program, [log_file], "trusted", {}), max(3, repeat // 2)), n,
                            "lines/s", c, note="your file, {:,} lines".format(n)))
        # ---- Nova_Stats: 50 dashboard ticks on recorded fixtures
        stats_dir = WORK / "poc/nova_stats"
        stats_program = stats_dir / "tests/bench.nova"
        stats_grants = {"read": [str(stats_dir)], "import_from": [str(stats_dir)], "clock": True, "process": True,
                   "regex": True}   # Nova_Stats needs replace_all, which only the regex grant defines (G-050)
        c = compile_ms(stats_program)
        ticks = 50
        rows.append(row("Nova_Stats: {} dashboard ticks (6 readers, model, 2 renders, JSON)".format(ticks), "poc",
                        "trusted", sample(lambda: run_once(stats_program, [str(ticks)], "trusted", {}, cwd=stats_dir),
                                          repeat), ticks, "ticks/s", c))
        if restricted_ok:
            rows.append(row("Nova_Stats: {} dashboard ticks (6 readers, model, 2 renders, JSON)".format(ticks), "poc",
                            "restricted", sample(lambda: run_once(stats_program, [str(ticks)], "restricted", stats_grants,
                                                                  cwd=stats_dir), repeat), ticks, "ticks/s", c))
        # ---- the 50 MB benchmark
        if full:
            big = os.path.join(folder, "big.log")
            print("generating the 50 MB log ...", file=sys.stderr)
            generate([str(WORK / "poc/nova_log/make_log.py"), big, "50"], big)
            n = count_lines(big)
            rows.append(row("Nova_Log: 50 MB synthetic access log", "full", "trusted",
                            sample(lambda: run_once(log_program, [big], "trusted", {}), 3, warmup=0), n, "lines/s", compile_ms(log_program),
                            note="{:,} lines; 3 samples; trusted only (the sandbox refuses a string over 1,000,000 chars)".format(n)))
    return rows
